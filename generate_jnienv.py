
#!/usr/bin/env python3

import re
import sys
from pathlib import Path


DECLARATION_RE = re.compile(
    r"JNIEXPORT\s+(.*?)\s*JNICALL\s+"
    r"gojni_(\w+)\s*\((.*?)\)\s*;",
    re.DOTALL,
)


def split_parameters(params):
    """Split a C parameter list into individual parameters."""
    params = params.strip()

    if not params or params == "void":
        return []

    return [p.strip() for p in params.split(",")]


def parameter_name(param):
    """Extract the name from a simple C parameter declaration."""
    match = re.search(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?$", param.strip())

    if not match:
        raise ValueError(f"Cannot parse parameter name: {param}")

    return match.group(1)


def generate_function(return_type, name, params):
    parameters = split_parameters(params)
    is_variadic = parameters and parameters[-1] == "..."

    named_params = parameters[:-1] if is_variadic else parameters
    names = [parameter_name(p) for p in named_params]

    signature = (
        f"static inline {return_type.strip()} JNICALL "
        f"gojni_{name}({params.strip()})"
    )

    if is_variadic:
        if not names:
            raise ValueError(f"Variadic function has no named parameters: {name}")

        last_named = names[-1]
        forwarded = ", ".join(names)

        # JNI provides a corresponding V variant for these methods.
        v_name = name + "V"

        call = f"(*env)->{v_name}({forwarded}, ap)"

        body = [
            "{",
            "    va_list ap;",
            f"    va_start(ap, {last_named});",
        ]

        if return_type.strip() == "void":
            body.append(f"    {call};")
            body.append("    va_end(ap);")
        else:
            body.append(f"    {return_type.strip()} result = {call};")
            body.append("    va_end(ap);")
            body.append("    return result;")

        body.append("}")
        return signature + " " + "\n".join(body)

    forwarded = ", ".join(names)
    call = f"(*env)->{name}({forwarded})"

    if return_type.strip() == "void":
        body = f"{{\n    {call};\n}}"
    else:
        body = f"{{\n    return {call};\n}}"

    return signature + " " + body


def main():
    header = Path(sys.argv[1] if len(sys.argv) > 1 else "jnienv.inc")
    output = Path(sys.argv[2] if len(sys.argv) > 2 else "jnienv.h")

    source = header.read_text(encoding="utf-8")
    declarations = list(DECLARATION_RE.finditer(source))

    if not declarations:
        sys.exit(f"No JNI wrapper declarations found in {header}")

    functions = []

    for declaration in declarations:
        return_type, name, params = declaration.groups()

        try:
            functions.append(
                generate_function(return_type, name, params)
            )
        except ValueError as exc:
            sys.exit(f"Error generating gojni_{name}: {exc}")

    generated = (
        "/* Generated by generate_jnienv.py; do not edit manually. */\n"
        "#ifndef __JNIENV_H__\n"
        "#define __JNIENV_H__\n\n"
        "#include <jni.h>\n"
        "#include <stdarg.h>\n\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        + "\n\n".join(functions) +
        "\n\n#ifdef __cplusplus\n}\n#endif\n\n"
        "#endif"
    )

    output.write_text(generated, encoding="utf-8")
    print(f"Generated {len(functions)} functions in {output}")


if __name__ == "__main__":
    main()
